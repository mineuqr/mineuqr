function buildCatalogSheet(
  workbook: ExcelJS.Workbook,
  ctx: {
    bundle: RestaurantReportingExportBundle;
    labels: ReportingExportLabels;
  }
) {
  const { bundle, labels } = ctx;
  const sheet = workbook.addWorksheet(sanitizeSheetName(labels.catalog));
  const lang = bundle.language;
  const catalog = bundle.catalog;

  styleSectionTitle(sheet, 1, 2, labels.catalog, lang);
  writeStyledTable(
    sheet,
    3,
    [labels.metric, labels.value],
    [
      [labels.categories, String(catalog.categoryCount)],
      [labels.items, String(catalog.itemCount)],
      [labels.menuVisits, String(catalog.menuVisits)],
    ],
    lang,
    new Set(),
    "#,##0"
  );

  sheet.mergeCells(8, 1, 8, 2);
  sheet.getCell(8, 1).value = labels.catalogPlaceholderTitle;
  sheet.getCell(8, 1).font = restaurantFont(lang);
  sheet.mergeCells(9, 1, 10, 2);
  sheet.getCell(9, 1).value = labels.catalogPlaceholderBody;
  sheet.getCell(9, 1).font = periodFont(lang);
  sheet.getCell(9, 1).fill = solidFill(REPORT_THEME.brandBanner);
  sheet.getCell(9, 1).alignment = {
    ...reportAlignment(lang, isRtl(lang) ? "right" : "left", 1),
    wrapText: true,
    vertical: "top",
  };
  sheet.getRow(9).height = 48;

  sheet.mergeCells(12, 1, 12, 2);
  sheet.getCell(12, 1).value = labels.topSellersNote;
  sheet.getCell(12, 1).font = metaFont(lang);

  applyPrintSetup(sheet, lang, { freezeAt: 3 });
}

async function buildRevenueTrendSheet(
  workbook: ExcelJS.Workbook,
  ctx: {
    bundle: RestaurantReportingExportBundle;
    labels: ReportingExportLabels;
    currencyFmt: string;
  }
) {
  const { bundle, labels, currencyFmt } = ctx;
  const sheet = workbook.addWorksheet(sanitizeSheetName(labels.revenueTrend));
  const lang = bundle.language;
  const points = bundle.revenueTrend.points;

  styleSectionTitle(sheet, 1, 4, labels.revenueTrend, lang);
  sheet.getCell(2, 1).value = labels.chartRevenueTrend;
  sheet.getCell(2, 1).font = periodFont(lang);

  const end = writeStyledTable(
    sheet,
    4,
    [
      labels.periodKey,
      labels.paidCheckCount,
      labels.revenue,
      labels.taxCollected,
    ],
    points.map((p) => [
      p.periodKey,
      p.paidCheckCount,
      parseDtoAmountForDisplay(p.revenue),
      parseDtoAmountForDisplay(p.taxCollected),
    ]),
    lang,
    new Set([2, 3]),
    currencyFmt
  );

  await maybeAddChartImage(
    workbook,
    sheet,
    0,
    end + 1,
    labels.chartRevenueTrend,
    points.map((p) => p.periodKey),
    [
      {
        label: labels.revenue,
        values: points.map((p) => parseDtoAmountForDisplay(p.revenue)),
      },
    ]
  );

  applyPrintSetup(sheet, lang, { landscape: true, freezeAt: 4 });
}

async function buildOrderSalesSheet(
  workbook: ExcelJS.Workbook,
  ctx: {
    bundle: RestaurantReportingExportBundle;
    labels: ReportingExportLabels;
    currencyFmt: string;
  }
) {
  const { bundle, labels, currencyFmt } = ctx;
  const sheet = workbook.addWorksheet(sanitizeSheetName(labels.orderSalesRollup));
  const lang = bundle.language;
  const periods = bundle.orderSalesRollup.periods;

  styleSectionTitle(sheet, 1, 4, labels.orderSalesRollup, lang);
  sheet.mergeCells(2, 1, 2, 4);
  sheet.getCell(2, 1).value = labels.revenueVsOrderSales;
  sheet.getCell(2, 1).font = periodFont(lang);
  sheet.getCell(2, 1).fill = solidFill(REPORT_THEME.brandLight);

  const end = writeStyledTable(
    sheet,
    4,
    [
      labels.periodKey,
      labels.orderCount,
      labels.completedOrders,
      labels.orderSales,
    ],
    periods.map((p) => [
      p.periodKey,
      p.orderCount,
      p.completedOrders,
      parseDtoAmountForDisplay(p.orderSales),
    ]),
    lang,
    new Set([3]),
    currencyFmt
  );

  await maybeAddChartImage(
    workbook,
    sheet,
    0,
    end + 1,
    labels.chartOrderTrend,
    periods.map((p) => p.periodKey),
    [
      {
        label: labels.orderSales,
        values: periods.map((p) => parseDtoAmountForDisplay(p.orderSales)),
      },
      {
        label: labels.orderCount,
        values: periods.map((p) => p.orderCount),
      },
    ]
  );

  applyPrintSetup(sheet, lang, { landscape: true, freezeAt: 4 });
}
